#!/usr/bin/env python3
"""Render the immutable native-mode host reports without promoting the suite."""

import argparse
import csv
import io
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "results/native-778d519f001d"


def render():
    rows = []
    quality = []
    fingerprints = {}
    for host, expected in [("a2", 180), ("galaxy", 60)]:
        report = json.loads((ROOT / host / "report.json").read_text())
        assert report["status"] == "complete" and len(report["rows"]) == expected
        assert report["commit"] == "778d519f001d25806b335a45a91b2740909e0a0b"
        for row in report["rows"]:
            assert row["invalid"] == 0 and row["deterministic"]
            key = (row["benchmark"], row["mode"])
            fingerprint = row["paf_without_timing_sha256"]
            assert fingerprints.setdefault(key, fingerprint) == fingerprint
        for benchmark in ["B01", "B02", "B03", "B04", "B05"]:
            for threads in report["threads"]:
                groups = {mode: [row for row in report["rows"] if row["benchmark"] == benchmark
                                 and row["threads"] == threads and row["mode"] == mode]
                          for mode in report["modes"]}
                baseline_wall = statistics.median(row["wall_s"] for row in groups["default"])
                baseline_map = statistics.median(row["mapping_s"] for row in groups["default"])
                for mode, group in groups.items():
                    wall = statistics.median(row["wall_s"] for row in group)
                    mapping = statistics.median(row["mapping_s"] for row in group)
                    rows.append(dict(host=host, benchmark=benchmark, threads=threads, mode=mode,
                                     wall_s=f"{wall:.2f}", mapping_s=f"{mapping:.3f}",
                                     wall_speedup=f"{baseline_wall / wall:.2f}",
                                     mapping_speedup=f"{baseline_map / mapping:.2f}",
                                     peak_rss_gib=f"{max(row['peak_rss_kb'] for row in group) / 1048576:.2f}"))
        for mode in report["modes"]:
            group = [row for row in report["rows"] if row["benchmark"] == "B02" and row["mode"] == mode]
            keys = ["mapped", "truth_overlap_correct", "endpoints_1kb", "mapq_unavailable", "wrong_mapq60"]
            assert len({tuple(row[key] for key in keys) for row in group}) == 1
            quality.append((host, mode, *[group[0][key] for key in keys]))
    table = io.StringIO()
    writer = csv.DictWriter(table, fieldnames=list(rows[0]), delimiter="\t", lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows)
    text = """# Native Adaptive Host Results

Generated by `python3 benchmarks/scripts/report_native.py`; use `--check` to verify.

## Provenance

Measured 2026-09-12/13 at commit `778d519f001d25806b335a45a91b2740909e0a0b`,
before the 1.6.0 version bump. The measured binary reports 1.5.0; these artifacts
have not been relabeled as measurements of the release commit.

Both runs completed: a2 has 180 measurements (three repeats); galaxy has 60
(one repeat). All rows passed the driver's PAF validation and determinism checks.
Normalized PAF hashes agree across repeats, worker counts, and architectures
within every benchmark/mode. These checks do not prove general mapping accuracy.

This is a native-only, same-binary mode comparison on registered B01-B05 inputs,
using Containment with k=25, r=0.01, threshold=0.4, min_diff=0.075, overlap=0.3.
It is not the maintained suite gate, an old-release comparison, or a comparison
against another mapper. Inputs were page-cache warmed and PAF was written to disk.
Every invocation rebuilt its index; cache reuse and cold-cache operation were not tested.

- `default`: original mapper, default indexing and dispatch.
- `adaptive`: compact index, adaptive mapping, read batches of 64.
- `dense`: adaptive configuration plus regional dense repeat rescue.
- `parsing`: adaptive configuration plus two additional query parser workers.

Parser workers are additional to the listed mapping workers, not free resources.
Modes bundle changes; these ratios cannot attribute gains to individual changes.
a2 timings are medians of three; galaxy timings are single observations, not
confidence intervals. Peak RSS is the maximum observed across repeats.

## Main Result

B04 is real HiFi at 10x depth. Adaptive parsing gives the following whole-run
and mapping-only results relative to default mode at the same mapping worker count:

| Host | Mapping Workers | Wall (s) | Wall Speedup | Mapping (s) | Mapping Speedup | Peak RSS (GiB) |
| --- | ---: | ---: | ---: | ---: | ---: | ---: |
"""
    for row in rows:
        if row["benchmark"] == "B04" and row["mode"] == "parsing":
            text += f"| {row['host']} | {row['threads']} | {row['wall_s']} | {row['wall_speedup']}x | {row['mapping_s']} | {row['mapping_speedup']}x | {row['peak_rss_gib']} |\n"
    text += """
No 10x improvement was demonstrated. Dense mode is slower end-to-end in every
measured configuration: repeat-index construction alone takes 178-395 seconds,
with peak RSS about 26.6 GiB. It should remain experimental. ONT B05 regresses
end-to-end in every experimental mode; B01-B03 also regress at 16/64 workers,
where index setup offsets mapping gains. Do not enable adaptive mode universally.

## Simulated Placement

B02 contains 125,000 reads. Correct placement requires the true segment AND
strand with interval IoU above 0.1. Both endpoints must be within 1,000 bases for
the endpoint count. MAPQ 255 is unavailable, not confidence. Real-read mapping
counts are not accuracy; cross-individual and split-read accuracy remain unvalidated.

| Host | Mode | Mapped | Correct Placement | Endpoints Within 1 kb | MAPQ Unavailable | Wrong MAPQ 60 |
| --- | --- | ---: | ---: | ---: | ---: | ---: |
"""
    for entry in quality:
        text += "| " + " | ".join(map(str, entry)) + " |\n"
    text += """
Dense rescue adds only four correct placements under this criterion despite its
indexing cost. Adaptive coordinates remain estimates, not base-level alignments.

## Full Matrix

[results.tsv](results.tsv) contains every host/benchmark/worker/mode aggregate.
The reports below retain all individual measurements, exact commands, dataset
identities, binary hashes, and normalized PAF hashes.

- [a2 report](a2/report.json), [run log](a2/run.log), [raw diagnostics](a2/raw-profiles.tar.gz)
- [galaxy report](galaxy/report.json), [run log](galaxy/run.log), [raw diagnostics](galaxy/raw-profiles.tar.gz)

Raw diagnostic archives contain the original profiles, timing files, and stderr.
Large PAFs remain on their respective hosts under
`~/bench-results/native-778d519f001d-{host}/raw/` (a2: about 28 GB; galaxy: 9.1 GB).
No measured file or current suite baseline was replaced by this experiment.

Report SHA-256:

```text
a2      ef1136a827d237cca3f1c1dfab5ff7de1569b4161a96f48ab06cc12290130de3
galaxy  883c6776f389a1a2eca54cbb3248dec5f00712764b61744098d938ff1c02b6fd
```
"""
    return {"README.md": text, "results.tsv": table.getvalue()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in render().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"stale native report: {path}")
        else:
            path.write_text(content)
        print(f"{'checked' if args.check else 'wrote'} {path}")


if __name__ == "__main__":
    main()