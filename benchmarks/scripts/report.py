def regenerate(text: str, rs: dict, reg: dict) -> tuple[str, list[str], list[str]]:
    seen, unknown = [], []

    def sub(mo):
        name = mo.group("name")
        seen.append(name)
        fn = BUILDERS.get(name)
        if fn is None:
            unknown.append(name)
            return mo.group(0)
        body = fn(rs, reg)
        if not body.endswith("\n"):
            body += "\n"
        return mo.group(1) + body + mo.group(4)

    return BLOCK_RE.sub(sub, text), seen, unknown


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("result_set", nargs="?", help="default: the suite's current/")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if RESULTS.md would change (does not write)")
    ap.add_argument("--arch", default=None,
                    help="architecture whose results to use; default: this machine's "
                         "(x86_64, aarch64)")
    ap.add_argument("--stdout", action="store_true", help="print blocks instead of writing")
    a = ap.parse_args()

    if a.result_set:
        rs = load_set(Path(a.result_set))
    else:
        d = current_dir(load_suite()["suite_version"], a.arch)
        if not d.is_dir():
            print(f"no baseline at {d}; pass a result set explicitly", file=sys.stderr)
            return 2
        rs = load_set(d)
    reg = load_registry()

    if a.stdout:
        for name, fn in BUILDERS.items():
            print(f"\n<!-- BEGIN GENERATED: {name} -->")
            print(fn(rs, reg), end="")
            print(f"<!-- END GENERATED: {name} -->")
        return 0

    changed, missing_all, seen_all = [], [], set()
    for target in TARGETS:
        if not target.exists():
            print(f"{target} does not exist", file=sys.stderr)
            return 2
        old = target.read_text()
        new, seen, unknown = regenerate(old, rs, reg)
        seen_all |= set(seen)
        if unknown:
            print(f"unknown generated block(s) in {target.name}: {', '.join(unknown)}",
                  file=sys.stderr)
            return 2
        if new != old:
            changed.append((target, new))

    missing = [b for b in BUILDERS if b not in seen_all]
    if missing:
        print(f"note: no marker anywhere for: {', '.join(missing)}", file=sys.stderr)

    if a.check:
        if changed:
            for t, _ in changed:
                print(f"{t.name} is out of date — run `python3 benchmarks/scripts/report.py`",
                      file=sys.stderr)
            return 1
        print(f"{', '.join(t.name for t in TARGETS)} are current with {rs['dir'].name}")
        return 0

    if not changed:
        print(f"{', '.join(t.name for t in TARGETS)} already current with {rs['dir'].name}")
        return 0
    for t, text in changed:
        t.write_text(text)
        print(f"regenerated {t.name} from {rs['dir'].name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
