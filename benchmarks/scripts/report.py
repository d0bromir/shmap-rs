def _carried_reference_row(m: dict) -> str:
    """Disclose a reference measurement older than the run it is compared with.

    `suite.toml` re-measures the C++ only when its binary changes, so an
    ordinary run carries the previous measurement forward. Every speedup ratio
    below then has a numerator and a denominator from different days -- on a
    host whose noise floor on identical work is over 20%, that is something the
    reader has to be told, not something to leave in a manifest.
    """
    c = m.get("reference_rows_carried_forward")
    if not c:
        return ""
    impls = ", ".join(f"`{i}`" for i in c.get("impls", []))
    return (f"| reference measurement | {impls} not re-measured for this run: "
            f"{c.get('rows', '?')} rows carried forward from `{c.get('from_commit', '?')}`, "
            f"measured **{c.get('measured', '?')}**. The binary is unchanged, so the figures "
            f"stand, but every speedup below divides this run's time by that day's. |\n")


def block_summary(rs: dict) -> str:
    rows, idx = rs["rows"], index(rs["rows"])
    speed1, speed4, rss_rs, rss_cpp, best = [], [], [], [], []

    for bid in benchmarks_in(rows):
        for m in metrics_in(rows, bid):
            r1 = idx.get((bid, SUBJECT, m, 1))
            c1 = idx.get((bid, REFERENCE, m, 1))
            if r1 and c1:
                speed1.append(c1["wall_s"] / r1["wall_s"])
                r4 = idx.get((bid, SUBJECT, m, 4))
                if r4:
                    speed4.append(c1["wall_s"] / r4["wall_s"])
                rss_rs.append(r1["peak_rss_kb"])
                rss_cpp.append(c1["peak_rss_kb"])
            if r1:
                ts = [r for r in rows if r["benchmark"] == bid and r["impl"] == SUBJECT
                      and r["metric"] == m]
                if ts:
                    fastest = min(ts, key=lambda r: r["wall_s"])
                    best.append((r1["wall_s"] / fastest["wall_s"], fastest["threads"], m, bid))

    L = ["| | |", "|---|---|"]
    if speed1:
        L.append(f"| Speed vs C++ `shmap`, single-threaded | **{rng(speed1)}** |")
    if speed4:
        L.append(f"| Speed vs C++ at `-@ 4` | **{rng(speed4)}** "
                 f"(the C++ cannot use more than one core) |")
    if rss_rs and rss_cpp:
        span = gb(min(rss_rs)) if gb(min(rss_rs)) == gb(max(rss_rs)) \
            else f"{gb(min(rss_rs))} – {gb(max(rss_rs))}"
        L.append(f"| Peak memory, `-@1` | **{span} vs {gb(max(rss_cpp))}"
                 f" — {ratio(max(rss_cpp)/max(rss_rs))}x less** |")
        # The single-threaded figure is not the whole story: each worker owns
        # its own bucket accumulator and per-read state, so memory grows with
        # thread count, and it grows much faster on deep read sets. Reporting
        # only -@1 would let someone size a machine 4x too small.
        worst = max((r["peak_rss_kb"], r["threads"], r["benchmark"])
                    for r in rows if r["impl"] == SUBJECT)
        if worst[0] > max(rss_rs) * 1.2:
            L.append(f"| Peak memory, worst case | **{gb(worst[0])}** at `-@{worst[1]}` on "
                     f"{worst[2]} — {ratio(max(rss_cpp)/worst[0])}x less than the C++. "
                     f"Memory grows with threads; see §3c |")
    if best:
        sp, th, m, bid = max(best)
        L.append(f"| Best whole-run thread speedup | **{sp:.2f}x** (`-@ {th}`, {m}, {bid}) |")

    det = [c for c in rs["checks"] if c["check"] == "thread_determinism"]
    if det:
        ok = sum(1 for c in det if c["passed"])
        L.append(f"| Determinism | output byte-identical across all thread counts "
                 f"({ok}/{len(det)} benchmark×metric combinations) |" if ok == len(det)
                 else f"| Determinism | **{len(det)-ok} of {len(det)} combinations DIFFER** |")
    return "\n".join(L) + "\n"


def block_versus_cpp(rs: dict) -> str:
    rows, idx = rs["rows"], index(rs["rows"])
    ca = agreement_of(rs["checks"])
    out = []

    for bid in benchmarks_in(rows):
        if not any(r["impl"] == REFERENCE and r["benchmark"] == bid for r in rows):
            continue
        reads, ref = dataset_of(bid, rows)
        out.append(f"### {bid} — {title_of(bid)}\n")
        out.append(f"Reads `{reads}` against `{ref}`. Single-threaded is the like-for-like "
                   f"column; the C++ has no threading and its figure is the median of three runs.\n")
        hdr = ["metric"] + [f"shmap-rs `-@{t}`" for t in HEADLINE_THREADS] + \
              ["C++"] + [f"speedup `-@{t}`" for t in HEADLINE_THREADS] + ["rs RSS", "C++ RSS"]
        out.append("| " + " | ".join(hdr) + " |")
        out.append("|" + "---|" + "---:|" * (len(hdr) - 1))
        for m in metrics_in(rows, bid):
            c1 = idx.get((bid, REFERENCE, m, 1))
            if not c1:
                continue
            rt = [idx.get((bid, SUBJECT, m, t)) for t in HEADLINE_THREADS]
            if not rt[0]:
                continue
            cells = [f"{r['wall_s']:.2f} s" if r else "—" for r in rt]
            sp = [f"**{c1['wall_s']/r['wall_s']:.2f}x**" if r else "—" for r in rt]
            label = m + (" *(no refinement)*" if m == "bucket_SH" else "")
            out.append(f"| {label} | " + " | ".join(cells) +
                       f" | {c1['wall_s']:.2f} s | " + " | ".join(sp) +
                       f" | {gb(rt[0]['peak_rss_kb'])} | {gb(c1['peak_rss_kb'])} |")
        out.append("")
        out.append("| metric | mapped | mapq 60 | agreement with C++ (12 core PAF cols) |")
        out.append("|---|---:|---:|---:|")
        for m in metrics_in(rows, bid):
            r1 = idx.get((bid, SUBJECT, m, 1))
            if not r1:
                continue
            a = ca.get((bid, m))
            out.append(f"| {m} | {num(r1['mapped'])} | {num(r1['mapq60'])} | "
                       + (f"**{a*100:.2f}%**" if a is not None else "—") + " |")
        out.append("")
    return "\n".join(out)


def block_thread_scaling(rs: dict) -> str:
    rows, idx = rs["rows"], index(rs["rows"])
    out = []
    for bid in benchmarks_in(rows):
        ms = metrics_in(rows, bid)
        threads = sorted({r["threads"] for r in rows
                          if r["benchmark"] == bid and r["impl"] == SUBJECT})
        if len(threads) < 2:
            continue
        reads, _ = dataset_of(bid, rows)
        out.append(f"### {bid} — {title_of(bid)} (`{reads}`)\n")
        # "best" because it is max() over the metrics, which is Jaccard: it is
        # slowest at -@1 and so has the most room to recover. Unlabelled, the
        # column reads as Containment's and overstates it by ~1.2x.
        out.append("| `-@` | " + " | ".join(ms) + " | best speedup vs `-@1` |")
        out.append("|---:|" + "---:|" * (len(ms) + 1))
        for t in threads:
            cells, sps = [], []
            for m in ms:
                r = idx.get((bid, SUBJECT, m, t))
                b = idx.get((bid, SUBJECT, m, 1))
                cells.append(f"{r['wall_s']:.2f} s" if r else "—")
                if r and b:
                    sps.append(b["wall_s"] / r["wall_s"])
            best = f"{max(sps):.2f}x" if sps else "—"
            out.append(f"| {t} | " + " | ".join(cells) + f" | {best} |")
        out.append("")
    return "\n".join(out)


def block_datasets(rs: dict, reg: dict) -> str:
    used = sorted({r[k] for r in rs["rows"] for k in ("reference_id", "reads_id")})
    out = ["| id | kind | records | bases | mean len | path |",
           "|---|---|---:|---:|---:|---|"]
    for d in used:
        e = reg.get(d)
        if not e:
            continue
        recs, bases = int(e["records"]), int(e["bases"])
        out.append(f"| `{d}` | {e['kind']} | {num(recs)} | {num(bases)} | "
                   f"{num(bases // recs) if recs else '—'} | `{e.get('rel', e['path'])}` |")
    return "\n".join(out) + "\n"


def block_checks(rs: dict) -> str:
    if not rs["checks"]:
        return "_No checks recorded in this result set._\n"
    out = ["| check | benchmark | metric | result | detail |", "|---|---|---|---|---|"]
    for c in sorted(rs["checks"], key=lambda c: (c["check"], c["benchmark"], c["metric"])):
        out.append(f"| {c['check']} | {c['benchmark']} | {c['metric']} | "
                   f"{'pass' if c['passed'] else '**FAIL**'} | {c['detail']} |")
    return "\n".join(out) + "\n"


def _profiles(rs: dict, section: str = "timers_secs") -> dict[tuple, dict]:
    """(benchmark, metric, threads) -> one section of the run's own `-x` reports.

    `section` selects `timers_secs` (stage times) or `counters` (the per-read
    work counters §5b reports). Both live in the same JSON, so the two tables
    cannot come from different runs.

    Read from `raw-profiles.tar.gz` if present, else the loose `raw/` directory.
    This is what keeps the profiling tables in step with the benchmark tables:
    both come out of the same result set, so they cannot drift apart the way
    they did when §5 was maintained by hand from a separate profiling run.
    """
    import tarfile

    out: dict[tuple, dict] = {}

    # Anchored rather than split("_"): metric names contain underscores
    # (`bucket_SH`, `bucket_LCS`), so a positional split silently drops exactly
    # the no-refinement metric the refine tables exist to contrast against.
    fn = re.compile(r"^(?P<bench>[^_]+)_(?P<impl>[^_]+)_(?P<metric>.+)_t(?P<t>\d+)_r\d+\.json$")

    def take(name: str, data: bytes):
        mo = fn.match(Path(name).name)
        if not mo or mo.group("impl") != "shmap-rs":
            return
        parts = (mo.group("bench"), mo.group("metric"))
        try:
            threads = int(mo.group("t"))
            j = json.loads(data)
        except (ValueError, json.JSONDecodeError):
            return
        t = j.get("global", {}).get(section)
        if t:
            out[(parts[0], parts[1], threads)] = t

    tgz = rs["dir"] / "raw-profiles.tar.gz"
    if tgz.exists():
        with tarfile.open(tgz) as tf:
            for m in tf.getmembers():
                if m.isfile() and m.name.endswith(".json"):
                    f = tf.extractfile(m)
                    if f:
                        take(m.name, f.read())
    else:
        for p in (rs["dir"] / "raw").glob("*.json"):
            take(p.name, p.read_bytes())
    return out


