def block_memory_scaling(rs: dict) -> str:
    """Peak RSS against thread count.

    Each worker owns its own `Buckets` accumulator and per-read scratch, so
    memory is a function of thread count as well as input. On a shallow set the
    growth is slight; on a deep one it is several-fold, and the headline
    single-threaded figure badly understates what a 64-thread run needs.
    """
    rows, idx = rs["rows"], index(rs["rows"])
    threads = sorted({r["threads"] for r in rows if r["impl"] == SUBJECT})
    out = ["| benchmark | " + " | ".join(f"`-@{t}`" for t in threads) + " | growth |",
           "|---|" + "---:|" * (len(threads) + 1)]
    for bid in benchmarks_in(rows):
        vals = [idx.get((bid, SUBJECT, "Containment", t)) for t in threads]
        if not vals[0]:
            continue
        cells = [gb(v["peak_rss_kb"]) if v else "—" for v in vals]
        got = [v["peak_rss_kb"] for v in vals if v]
        out.append(f"| {bid} | " + " | ".join(cells) +
                   f" | **{max(got)/got[0]:.1f}x** |")
    return "\n".join(out) + "\n"


def block_phase_split(rs: dict) -> str:
    """Index vs mapping vs total, per benchmark, per implementation.

    Indexing is a fixed cost set by the reference, not the read set, and it is
    largely serial. Mapping is what scales with reads and threads. A whole-run
    speedup mixes the two, and the mix changes with depth — so the same code
    looks very different at 1x and 10x unless the phases are shown apart.

    `SUBJECT` gets this from its own `-x`/`--profile-log` report (wall timers
    for the `indexing`/`mapping` brackets). `REFERENCE` (the C++) emits no
    such report, so `run.py`'s `measure` gets it a different way — Pesho's
    method: a second run of the identical command against a single read
    (indexing does not depend on the read set, so that run's wall time is
    almost entirely indexing), with mapping time recovered by subtracting it
    from the real run's wall time. Both columns are the same two numbers
    either way, so they are directly comparable here despite coming from
    different measurement methods.
    """
    rows, idx = rs["rows"], index(rs["rows"])
    out = ["| benchmark | impl | `-@` | index | mapping | total | index share | mapping speedup |",
           "|---|---|---:|---:|---:|---:|---:|---:|"]
    any_row = False
    for bid in benchmarks_in(rows):
        threads = sorted({r["threads"] for r in rows
                          if r["benchmark"] == bid and r["impl"] == SUBJECT})
        base = idx.get((bid, SUBJECT, "Containment", 1))
        for t in threads:
            r = idx.get((bid, SUBJECT, "Containment", t))
            if not r or r.get("index_s") in (None, "") or r.get("map_s") in (None, ""):
                continue
            i, m, w = float(r["index_s"]), float(r["map_s"]), r["wall_s"]
            sp = (float(base["map_s"]) / m) if (base and base.get("map_s") and m > 0) else None
            out.append(f"| {bid} | {SUBJECT} | {t} | {i:.2f} s | {m:.2f} s | {w:.2f} s | "
                       f"{i/w*100:.0f}% | " + (f"{sp:.2f}x |" if sp else "— |"))
            any_row = True
        ref_threads = sorted({r["threads"] for r in rows
                              if r["benchmark"] == bid and r["impl"] == REFERENCE})
        for t in ref_threads:
            r = idx.get((bid, REFERENCE, "Containment", t))
            if not r or r.get("index_s") in (None, "") or r.get("map_s") in (None, ""):
                continue
            i, m, w = float(r["index_s"]), float(r["map_s"]), r["wall_s"]
            out.append(f"| {bid} | {REFERENCE} | {t} | {i:.2f} s | {m:.2f} s | {w:.2f} s | "
                       f"{i/w*100:.0f}% | — |")
            any_row = True
        out.append("| | | | | | | | |")
    if not any_row:
        return ("_This result set predates the index/mapping split; re-run to populate._\n")
    return "\n".join(out) + "\n"


def block_readme_pitch(rs: dict) -> str:
    """README's one-line claim, at headline precision.

    Generated for the same reason as the table below it: it is the first number
    a reader sees, and it sat one line above a generated block while being
    maintained by hand. Rounded to one decimal deliberately — a pitch reads
    better as 1.9-2.3x than 1.86-2.27x — but rounded FROM the measurement rather
    than from memory.
    """
    rows, idx = rs["rows"], index(rs["rows"])
    sp, best, rss_rs, rss_cpp = [], [], [], []
    for bid in benchmarks_in(rows):
        for m in metrics_in(rows, bid):
            r1 = idx.get((bid, SUBJECT, m, 1))
            c1 = idx.get((bid, REFERENCE, m, 1))
            if r1 and c1:
                sp.append(c1["wall_s"] / r1["wall_s"])
                rss_rs.append(r1["peak_rss_kb"])
                rss_cpp.append(c1["peak_rss_kb"])
            if r1:
                ts = [r for r in rows if r["benchmark"] == bid and r["impl"] == SUBJECT
                      and r["metric"] == m]
                if ts:
                    best.append(r1["wall_s"] / min(ts, key=lambda r: r["wall_s"])["wall_s"])
    if not (sp and best and rss_rs):
        return "_No reference-implementation rows in this result set._\n"
    worst_rss = max(r["peak_rss_kb"] for r in rows if r["impl"] == SUBJECT)
    return (f"Against the C++ original on real whole-genome data: "
            f"**{rng(sp, '{:.1f}')} faster single-threaded, up to {max(best):.1f}x\n"
            f"with threads**, with identical mapping counts. Memory is "
            f"~{ratio(max(rss_cpp)/max(rss_rs))}x lower single-threaded "
            f"({gb(max(rss_rs))} against {gb(max(rss_cpp))}) — but it grows with thread count, "
            f"reaching {gb(worst_rss)} at the highest, so size for the run you intend.\n")


def block_readme_summary(rs: dict) -> str:
    """README.md's at-a-glance table.

    README used to carry these figures by hand and they drifted: it advertised
    46.2 s against the C++'s 98.3 s long after the measured pair was 47.6 and
    104.1, and a 13.63x thread speedup after it had become 16.23x. Nothing
    caught it because `--check` only ever looked at RESULTS.md. Now it does not
    need catching.
    """
    rows, idx = rs["rows"], index(rs["rows"])
    cfg = load_suite().get("report", {})
    labels = cfg.get("readme_labels", {})
    out = ["| dataset | shmap-rs `-@1` | shmap-rs `-@4` | C++ `shmap` | speedup | memory |",
           "|---|---:|---:|---:|---:|---:|"]
    for bid in cfg.get("readme_highlight", []):
        r1 = idx.get((bid, SUBJECT, "Containment", 1))
        r4 = idx.get((bid, SUBJECT, "Containment", 4))
        c1 = idx.get((bid, REFERENCE, "Containment", 1))
        if not (r1 and r4 and c1):
            continue
        out.append(
            f"| {labels.get(bid, bid)} | **{r1['wall_s']:.1f} s** | **{r4['wall_s']:.1f} s** | "
            f"{c1['wall_s']:.1f} s | **{c1['wall_s']/r1['wall_s']:.2f}x** / "
            f"{c1['wall_s']/r4['wall_s']:.2f}x | {gb(r1['peak_rss_kb'])} vs {gb(c1['peak_rss_kb'])} |")

    sp1, sp4, best = [], [], []
    for bid in benchmarks_in(rows):
        for m in metrics_in(rows, bid):
            r1, r4 = idx.get((bid, SUBJECT, m, 1)), idx.get((bid, SUBJECT, m, 4))
            c1 = idx.get((bid, REFERENCE, m, 1))
            if r1 and c1:
                sp1.append(c1["wall_s"] / r1["wall_s"])
                if r4:
                    sp4.append(c1["wall_s"] / r4["wall_s"])
            if r1:
                ts = [r for r in rows if r["benchmark"] == bid and r["impl"] == SUBJECT
                      and r["metric"] == m]
                if ts:
                    f = min(ts, key=lambda r: r["wall_s"])
                    best.append((r1["wall_s"] / f["wall_s"], f["threads"]))
    if sp1 and sp4:
        out += ["",
                f"Across all {len(benchmarks_in(rows))} benchmarks and three metrics: "
                f"**{rng(sp1)}** single-threaded, **{rng(sp4)}** at `-@4`. Every figure here is "
                f"generated from the current result set and checked in CI — see "
                f"[RESULTS.md](RESULTS.md)."]
    if best:
        sp, th = max(best)
        out += ["",
                f"- **Scales to many threads** — up to **{sp:.2f}x** whole-run at `-@ {th}`; the C++ "
                f"cannot use more than one core. Output is byte-identical at every thread count."]
    return "\n".join(out) + "\n"


def block_stage_breakdown(rs: dict) -> str:
    prof = _profiles(rs)
    if not prof:
        return ("_No `-x` profile reports in this result set._\n")
    rows = rs["rows"]
    out = []

    # --- what refinement costs, per benchmark, single-threaded --------------
    out.append("Shares of `query_mapping`, single-threaded. Indented rows are part of the row "
               "above.\n")
    for bid in benchmarks_in(rows):
        ms = [m for m in metrics_in(rows, bid) if (bid, m, 1) in prof]
        if not ms:
            continue
        out.append(f"**{bid}** — {title_of(bid)}\n")
        out.append("| stage | " + " | ".join(ms) + " |")
        out.append("|---|" + "---:|" * len(ms))
        for stage, depth in STAGES:
            cells = []
            for m in ms:
                t = prof[(bid, m, 1)]
                qm = t.get("query_mapping", 0.0)
                cells.append(f"{t[stage]/qm*100:.1f}%" if stage in t and qm else "—")
            if all(c == "—" for c in cells):
                continue
            label = ("⌐ " if depth else "") + f"`{stage}`"
            out.append(f"| {label} | " + " | ".join(cells) + " |")
        # absolute seconds give the shares meaning; a share can fall while the
        # cost rises if something else grew faster.
        out.append("| *`query_mapping` total* | "
                   + " | ".join(f"*{prof[(bid, m, 1)].get('query_mapping', 0):.1f} s*" for m in ms)
                   + " |")
        out.append("")

    # --- indexing against thread count -------------------------------------
    deep = max(benchmarks_in(rows), key=lambda b: sum(
        1 for r in rows if r["benchmark"] == b and r["impl"] == SUBJECT))
    threads = sorted({t for (b, m, t) in prof if b == deep and m == "Containment"})
    if len(threads) > 1:
        out.append(f"### Indexing against thread count ({deep}, Containment)\n")
        out.append("| stage | " + " | ".join(f"`-@{t}`" for t in threads) + " |")
        out.append("|---|" + "---:|" * len(threads))
        for stage in INDEX_STAGES:
            cells = [(f"{prof[(deep, 'Containment', t)][stage]:.1f}"
                      if stage in prof.get((deep, "Containment", t), {}) else "—")
                     for t in threads]
            if all(c == "—" for c in cells):
                continue
            out.append(f"| `{stage}` (s) | " + " | ".join(cells) + " |")
        out.append("")
    return "\n".join(out)


def block_seed_heuristic(rs: dict) -> str:
    """How much match-examining work the seed heuristic avoids.

    This is the algorithm's central claim — that pruning lets it keep every
    k-mer, frequent ones included, instead of discarding seeds the way every
    other mapper does. Stage timings (§5) say where the time goes; they cannot
    say whether the pruning is doing anything, because a heuristic that pruned
    nothing would show the same stage shares.

    `realized potential` is possible matches divided by matches actually
    examined: work avoided. `unrealized potential` is matches examined divided
    by matches in the reported mapping: work still wasted, and the headroom a
    sharper heuristic would attack.

    Single-threaded, since these are whole-run sums and the counters are
    thread-invariant (the output is byte-identical across thread counts).
    """
    rows = rs["rows"]
    ctr = _profiles(rs, "counters")
    if not ctr:
        return "_This result set carries no `-x` counters; re-run to populate._\n"
    out = ["| benchmark | metric | possible/read | examined/read | in mapping/read "
           "| realized | unrealized | seeded buckets/read | final buckets/read |",
           "|---|---|---:|---:|---:|---:|---:|---:|---:|"]
    any_row = False
    for bid in benchmarks_in(rows):
        for metric in metrics_in(rows, bid):
            c = ctr.get((bid, metric, 1))
            if not c:
                continue
            reads = c.get("reads", 0)
            poss, seen = c.get("possible_matches", 0), c.get("total_matches", 0)
            used = c.get("matches_in_reported_mappings", 0)
            if not (reads and seen and used):
                continue
            out.append(
                f"| {bid} | {metric} | {num(poss / reads)} | {num(seen / reads)} | "
                f"{num(used / reads)} | **{poss / seen:.1f}x** | {seen / used:.1f}x | "
                f"{c.get('seeded_buckets', 0) / reads:.1f} | "
                f"{c.get('final_buckets', 0) / reads:.2f} |")
            any_row = True
        out.append("| | | | | | | | | |")
    if not any_row:
        return "_This result set carries no match counters; re-run to populate._\n"
    return "\n".join(out) + "\n"


def block_concordance(rs: dict) -> str:
    """From the concordance_<mapper> check rows, which run.py records by joining
    against the cached external PAFs."""
    rows = [c for c in rs["checks"] if c["check"].startswith("concordance_")]
    if not rows:
        return ("_No concordance data in this result set — the external-mapper corpus had not been "
                "built when it was measured. Build it with `benchmarks/scripts/reference_mappers.py --run`, "
                "then a subsequent run will populate this._\n")

    def parse(detail: str) -> dict:
        out = {}
        for part in detail.split():
            if "=" in part:
                k, v = part.split("=", 1)
                try:
                    out[k] = float(v)
                except ValueError:
                    pass
        return out

    mappers = sorted({c["check"].removeprefix("concordance_") for c in rows})
    out = []
    for mapper in mappers:
        out.append(f"### vs {mapper}\n")
        out.append("| benchmark | metric | reference mapped | recall | agreement | **good** |")
        out.append("|---|---|---:|---:|---:|---:|")
        for c in sorted((c for c in rows if c["check"].endswith(mapper)),
                        key=lambda c: (c["benchmark"], c["metric"])):
            d = parse(c["detail"])
            out.append(f"| {c['benchmark']} | {c['metric']} | "
                       f"{num(d['ref']) if 'ref' in d else '—'} | "
                       f"{d.get('recall', float('nan')):.4f} | "
                       f"{d.get('agreement', float('nan')):.4f} | "
                       f"**{d.get('good', float('nan')):.4f}** |")
        out.append("")
    return "\n".join(out)


