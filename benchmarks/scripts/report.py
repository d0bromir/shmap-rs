# Thread counts shown in the "versus the C++" table. -@1 is the like-for-like
# column (the C++ has no threading); -@4 is shown because it is a fair desktop
# comparison, not because it is our best.
HEADLINE_THREADS = (1, 4)

BLOCK_RE = re.compile(
    r"(<!-- BEGIN GENERATED: (?P<name>[a-z0-9-]+) -->\n)(?P<body>.*?)(<!-- END GENERATED: (?P=name) -->)",
    re.DOTALL,
)


def gb(kb: float) -> str:
    return f"{kb / 1048576:.2f} GB"


def num(n) -> str:
    """Thin-space thousands separators, as the existing prose uses."""
    return f"{int(n):,}".replace(",", " ")


def rng(vals, fmt="{:.2f}", unit="x") -> str:
    """A range, collapsed to a single figure when the ends agree once rounded —
    "2.13–2.31x" is informative, "2.50–2.50x" just looks like a bug."""
    lo, hi = fmt.format(min(vals)), fmt.format(max(vals))
    return f"{lo}{unit}" if lo == hi else f"{lo}–{hi}{unit}"


def ratio(x: float) -> str:
    return f"{x:.0f}" if x >= 10 else f"{x:.1f}"


def index(rows: list[dict]) -> dict:
    return {(r["benchmark"], r["impl"], r["metric"], r["threads"]): r for r in rows}


def benchmarks_in(rows) -> list[str]:
    return sorted({r["benchmark"] for r in rows})


def metrics_in(rows, bid) -> list[str]:
    """Suite order, not alphabetical — Containment, Jaccard, bucket_SH reads as
    'default, stricter, none' and the prose depends on that order."""
    suite = load_suite()
    b = next((b for b in suite["benchmark"] if b["id"] == bid), None)
    present = {r["metric"] for r in rows if r["benchmark"] == bid}
    order = b["metrics"] if b else sorted(present)
    return [m for m in order if m in present]


def title_of(bid: str) -> str:
    b = next((b for b in load_suite()["benchmark"] if b["id"] == bid), None)
    return b["title"] if b else bid


def dataset_of(bid: str, rows: list[dict]) -> tuple[str, str]:
    r = next((r for r in rows if r["benchmark"] == bid), None)
    return (r["reads_id"], r["reference_id"]) if r else ("?", "?")


