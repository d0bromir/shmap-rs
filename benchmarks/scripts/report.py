#!/usr/bin/env python3
"""Regenerate the numbers in RESULTS.md and README.md from a result set.

  report.py                    regenerate from results/suite-<v>/current/
  report.py <result-set-dir>   regenerate from a specific set
  report.py --check            fail if any target is out of date (CI uses this)
  report.py --stdout           print the generated blocks instead of writing

Every number in RESULTS.md resolves to a row in `results.tsv`, which names its
dataset id, parameter set, metric, thread count and the exact command line. That
chain is the point (VERSIONING.md, "Traceability"): a reader can walk from a
figure in the prose back to the invocation that produced it.

---------------------------------------------------------------------------
What is generated and what is not
---------------------------------------------------------------------------
Only the regions between

    <!-- BEGIN GENERATED: <name> -->  ...  <!-- END GENERATED: <name> -->

are rewritten. Everything outside them is prose and is never touched.

VERSIONING.md says RESULTS.md is generated and never hand-edited. That is about
the *numbers*: the contradictory figures this project used to carry came from
tables edited by hand and then diverging. The analysis around them — why Jaccard
is slower than Containment, what dropping refinement costs — is not derivable
from a TSV and is written by people. Marking the generated regions keeps the
guarantee where it belongs without throwing the reasoning away.

Editing inside a generated block is pointless: the next run overwrites it, and
`--check` fails the build in the meantime.
"""

